    /**
     * Siapkan model ML Kit on-device jika bahasa yang dipilih didukung ML Kit (misal EN).
     * Untuk bahasa daerah (jv, su, mad) yang belum didukung model ML Kit resmi, sistem otomatis
     * menggunakan kamus lokal penuh + aturan morfologi/frasa daerah secara offline.
     */
    fun prepareHybridTranslator(langCode: String) {
        val norm = normalizeLang(langCode)
        if (norm == "en" && !mlKitTranslators.containsKey("en")) {
            try {
                val options = TranslatorOptions.Builder()
                    .setSourceLanguage(TranslateLanguage.INDONESIAN)
                    .setTargetLanguage(TranslateLanguage.ENGLISH)
                    .build()
                val translator = Translation.getClient(options)
                mlKitTranslators["en"] = translator
                val conditions = DownloadConditions.Builder().build()
                translator.downloadModelIfNeeded(conditions)
                    .addOnSuccessListener {
                        mlKitReadyLangs.add("en")
                        cacheByLang["en"]?.clear()
                    }
            } catch (_: Throwable) {
                // Tetap aman fallback ke kamus offline jika perangkat tanpa Play Services
            }
        }
    }

    fun autoTranslateText(sourceText: String, targetLang: String): String {
        val lang = normalizeLang(targetLang)
        if (sourceText.isBlank() || lang == "id") return sourceText

        val langCache = cacheByLang.getOrPut(lang) { mutableMapOf() }
        langCache[sourceText]?.let { return it }

        // 1. Prioritas pertama: Cek apakah teks cocok dengan entri kamus inti 5 bahasa
        val matchedKey = reverseIdLookup[sourceText.trim().lowercase()]
        if (matchedKey != null) {
            val dictHit = when (lang) {
                "en" -> enBase[matchedKey]
                "jv" -> jvBase[matchedKey]
                "su" -> suBase[matchedKey]
                "mad" -> madBase[matchedKey]
                else -> null
            }
            if (dictHit != null) {
                langCache[sourceText] = dictHit
                return dictHit
            }
        }

        // 2. Prioritas kedua (Hybrid): ML Kit on-device (untuk EN teks panjang/bebas) + kamus frasa/kata
        val translated = when (lang) {
            "en" -> {
                val enDirect = enBase.entries.find { it.value.equals(sourceText, ignoreCase = true) }?.value
                if (enDirect != null) {
                    enDirect
                } else {
                    if (mlKitReadyLangs.contains("en")) {
                        mlKitTranslators["en"]?.translate(sourceText)
                            ?.addOnSuccessListener { result ->
                                if (!result.isNullOrBlank()) {
                                    langCache[sourceText] = result
                                }
                            }
                    }
                    sourceText
                }
            }
            "jv", "su", "mad" -> {
                var out = sourceText
                for ((rule, madText) in phraseRules) {
                    val replacement = when (lang) {
                        "jv" -> rule.first
                        "su" -> rule.second
                        else -> madText
                    }
                    if (out.contains(rule.first, ignoreCase = true)) {
                        out = out.replace(rule.first, replacement, ignoreCase = true)
                    }
                }
                for ((keyWord, tri) in wordRules) {
                    val replacement = when (lang) {
                        "jv" -> tri.first
                        "su" -> tri.second
                        else -> tri.third
                    }
                    out = out.replace(Regex("\\b" + Regex.escape(keyWord) + "\\b", RegexOption.IGNORE_CASE), replacement)
                }
                out
            }
            else -> sourceText
        }

        langCache[sourceText] = translated
        return translated
    }

    fun normalizeLang(raw: String?): String {
        return when (raw?.trim()?.lowercase()) {
            "en", "english", "inggris" -> "en"
            "jv", "jw", "java", "jawa", "basa jawa" -> "jv"
            "su", "sundanese", "sunda", "basa sunda" -> "su"
            "mad", "madura", "madurese", "bhâsa madhurâ", "bhasa madhura" -> "mad"
            else -> "id"
        }
    }

    fun getLanguageDisplayName(langCode: String): String {
        return when (normalizeLang(langCode)) {
            "en" -> "English"
            "jv" -> "Basa Jawa"
            "su" -> "Basa Sunda"
            "mad" -> "Bhâsa Madhurâ"
            else -> "Bahasa Indonesia"
        }
    }

    fun loadSavedLanguage(context: Context): String {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val saved = normalizeLang(prefs.getString(KEY_LANG, "id"))
        _activeLanguage.value = saved
        prepareHybridTranslator(saved)
        return saved
    }

    fun setLanguage(context: Context, langCode: String) {
        val norm = normalizeLang(langCode)
        _activeLanguage.value = norm
        prepareHybridTranslator(norm)
        context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
            .edit()
            .putString(KEY_LANG, norm)
            .apply()
    }

    fun tr(key: String, lang: String = _activeLanguage.value): String {
        val norm = normalizeLang(lang)
        val baseId = idBase[key] ?: key.replace("_", " ")
        return when (norm) {
            "en" -> enBase[key] ?: autoTranslateText(baseId, "en")
            "jv" -> jvBase[key] ?: autoTranslateText(baseId, "jv")
            "su" -> suBase[key] ?: autoTranslateText(baseId, "su")
            "mad" -> madBase[key] ?: autoTranslateText(baseId, "mad")
            else -> baseId
        }
    }
